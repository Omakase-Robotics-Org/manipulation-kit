"""A hand's retarget map as a table of numbers, held joints included.

Every hand map in this package is, joint by joint, the same arithmetic: a
weighted mean of glove channels (flexion in [0, 1]), clamped to [0, 1],
optionally inverted, scaled onto an output interval and clamped to the
joint's limits — or a HELD joint, which reads no channel and is commanded to
a fixed value. :class:`RetargetTable` is that arithmetic written down as data,
so that

* a consumer can ask which joints are held, which channels each joint reads,
  and which joints a set of unusable channels leaves without an input —
  without probing the map with made-up poses (:meth:`RetargetTable.lacking`,
  :func:`drivability`);
* a program in another language can run the same map from a JSON document
  (:meth:`RetargetTable.to_json`, schema :data:`TABLE_SCHEMA`) and check
  itself against golden vectors that the Python map produced
  (:func:`golden_vectors`, schema :data:`GOLDEN_SCHEMA`).

The table of a model's DEFAULT map, and its golden vectors, are committed
beside the model (``hands/<maker>/<model>/retarget_table.json`` and
``retarget_golden.json``) and regenerated by ``mkit-retarget build``; a test
fails when they differ from what the code produces.

The evaluation rule, per joint, in descriptor order
---------------------------------------------------
1. A held joint is ``hold``, whatever the pose.
2. Otherwise, if any source channel (all weights are positive) has no
   reading, the joint is ``None`` (the consumer holds it where it is).
3. ``v = clamp(sum(w * flex) / sum(w), 0, 1)``; ``v = 1 - v`` if ``invert``.
4. ``out = lo + v * (hi - lo)``, then clamped to ``[clamp_lo, clamp_hi]``.

Output smoothing (``ema_alpha``) is state, not a map: it is recorded in the
table so a consumer can reproduce it, and is NOT applied by
:meth:`RetargetTable.evaluate`. Golden vectors are generated with smoothing
off.
"""
from __future__ import annotations

import hashlib
import json
import math
import random
from dataclasses import dataclass, replace
from typing import Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

from .joints import JointSpec

#: The ``schema`` string of a serialized :class:`RetargetTable`.
TABLE_SCHEMA = "manipulation_kit.retarget_table.v1"

#: The ``schema`` string of a golden-vector document (:func:`golden_vectors`).
GOLDEN_SCHEMA = "manipulation_kit.retarget_golden.v1"


@dataclass(frozen=True)
class TableRow:
    """One joint of a retarget map (see the module docstring for the rule)."""

    joint: JointSpec
    #: ``(channel, weight)``, weights > 0. Empty for a held joint.
    sources: Tuple[Tuple[str, float], ...]
    #: Output at flexion 0.0 (after ``invert``), in the joint's unit.
    lo: float
    #: Output at flexion 1.0 (after ``invert``), in the joint's unit.
    hi: float
    invert: bool = False
    #: The final clamp, in the joint's unit; ``None`` (the default) becomes
    #: the joint's limits. A held joint has no clamp.
    clamp_lo: Optional[float] = None
    clamp_hi: Optional[float] = None
    #: The value a held joint is commanded to; ``None`` = the joint follows.
    hold: Optional[float] = None

    def __post_init__(self):
        if self.hold is not None:
            for name in ("sources", "lo", "hi", "invert", "clamp_lo", "clamp_hi"):
                object.__setattr__(self, name, {"sources": (), "lo": 0.0, "hi": 0.0,
                                                "invert": False}.get(name))
            return
        if self.clamp_lo is None:
            object.__setattr__(self, "clamp_lo", float(self.joint.min))
        if self.clamp_hi is None:
            object.__setattr__(self, "clamp_hi", float(self.joint.max))

    @property
    def held(self) -> bool:
        return self.hold is not None

    def evaluate(self, flex: Mapping[str, Optional[float]]) -> Optional[float]:
        if self.hold is not None:
            return float(self.hold)
        acc, total = 0.0, 0.0
        for ch, w in self.sources:
            v = flex.get(ch)
            if v is None:
                return None
            acc += w * v
            total += w
        v = min(1.0, max(0.0, acc / total))
        if self.invert:
            v = 1.0 - v
        out = self.lo + v * (self.hi - self.lo)
        return min(self.clamp_hi, max(self.clamp_lo, out))

    def to_json(self) -> Dict[str, object]:
        j = self.joint
        out: Dict[str, object] = {"joint": j.name, "unit": j.unit, "min": j.min, "max": j.max}
        if self.hold is not None:
            out["hold"] = self.hold
            return out
        out.update(sources=[[ch, w] for ch, w in self.sources], lo=self.lo,
                   hi=self.hi, invert=self.invert, clamp=[self.clamp_lo, self.clamp_hi])
        return out

    @classmethod
    def from_json(cls, data: Mapping[str, object]) -> "TableRow":
        joint = JointSpec(str(data["joint"]), str(data["unit"]),
                          float(data["min"]), float(data["max"]))
        if "hold" in data:
            return cls(joint, (), 0.0, 0.0, hold=float(data["hold"]))
        clamp = data["clamp"]
        return cls(joint, tuple((str(c), float(w)) for c, w in data["sources"]),
                   float(data["lo"]), float(data["hi"]), bool(data["invert"]),
                   float(clamp[0]), float(clamp[1]))


@dataclass(frozen=True)
class RetargetTable:
    """A hand's whole map: one :class:`TableRow` per joint, descriptor order."""

    model: str
    rows: Tuple[TableRow, ...]
    ema_alpha: float = 0.0

    def __post_init__(self):
        for row in self.rows:
            j = row.joint
            if row.hold is not None:
                if not (math.isfinite(row.hold) and j.min <= row.hold <= j.max):
                    raise ValueError(f"{j.name}: hold {row.hold} leaves {j.min}..{j.max}")
                continue
            if not row.sources or any(not (w > 0) for _, w in row.sources):
                raise ValueError(f"{j.name}: a joint that follows needs channels "
                                 f"with positive weights, got {row.sources}")

    @property
    def joints(self) -> Tuple[JointSpec, ...]:
        return tuple(r.joint for r in self.rows)

    def held(self) -> Tuple[bool, ...]:
        """Per joint, descriptor order: ``True`` = held (reads no channel)."""
        return tuple(r.held for r in self.rows)

    def channels(self) -> Tuple[str, ...]:
        """Every channel a joint that follows reads, in joint order, each once
        (the map's ``required_channels()``)."""
        out: List[str] = []
        for r in self.rows:
            for ch, _ in r.sources:
                if ch not in out:
                    out.append(ch)
        return tuple(out)

    def channels_of(self, joint: str) -> Tuple[str, ...]:
        """The channels ``joint`` reads (empty when it is held)."""
        for r in self.rows:
            if r.joint.name == joint:
                return tuple(ch for ch, _ in r.sources)
        raise KeyError(joint)

    def lacking(self, unusable: Iterable[str]) -> Dict[str, Tuple[str, ...]]:
        """The joints left without an input when ``unusable`` channels have no
        reading, each with the unusable channels it reads. Held joints are
        never listed: they read nothing."""
        bad = set(unusable)
        out: Dict[str, Tuple[str, ...]] = {}
        for r in self.rows:
            missing = tuple(ch for ch, _ in r.sources if ch in bad)
            if missing:
                out[r.joint.name] = missing
        return out

    def holding(self, holds: Mapping[str, float]) -> "RetargetTable":
        """A copy with the joints in ``holds`` held at the given values."""
        names = {r.joint.name for r in self.rows}
        unknown = set(holds) - names
        if unknown:
            raise KeyError(f"no joint(s) {sorted(unknown)} in {self.model}")
        rows = tuple(replace(r, hold=float(holds[r.joint.name]))
                     if r.joint.name in holds else r for r in self.rows)
        return replace(self, rows=rows)

    def evaluate(self, flex: Mapping[str, Optional[float]]) -> List[Optional[float]]:
        """The map without smoothing: channel -> flexion (or ``None``) in, one
        target or ``None`` per joint out."""
        return [r.evaluate(flex) for r in self.rows]

    def to_json(self) -> Dict[str, object]:
        return {"schema": TABLE_SCHEMA, "model": self.model,
                "ema_alpha": self.ema_alpha,
                "joints": [r.to_json() for r in self.rows]}

    @classmethod
    def from_json(cls, data: Mapping[str, object]) -> "RetargetTable":
        if data.get("schema") != TABLE_SCHEMA:
            raise ValueError(f"schema must be {TABLE_SCHEMA!r}, got {data.get('schema')!r}")
        return cls(str(data["model"]),
                   tuple(TableRow.from_json(r) for r in data["joints"]),
                   float(data.get("ema_alpha", 0.0)))

    def dumps(self) -> str:
        """Canonical JSON text (sorted keys, two-space indent, final newline)."""
        return _dumps(self.to_json())

    def digest(self) -> str:
        """SHA-256 of :meth:`dumps`, hex: names this exact map."""
        return hashlib.sha256(self.dumps().encode("utf-8")).hexdigest()


def _dumps(doc: object) -> str:
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def retarget_table(model: str, config=None) -> RetargetTable:
    """The table of ``model``'s map (``config=None``: the model's defaults).

    Resolved through :func:`manipulation_kit.hands.get_retarget`; the mapper
    must provide ``table_rows()`` (every hand with a version-2 map does)."""
    from . import get_retarget  # noqa: PLC0415 — package imports this module

    mapper = get_retarget(model, config=config)
    rows = getattr(mapper, "table_rows", None)
    if rows is None:
        raise NotImplementedError(f"{model}: its retarget map has no table_rows()")
    return RetargetTable(model, tuple(rows()), float(getattr(mapper.cfg, "ema_alpha", 0.0)))


@dataclass(frozen=True)
class Drivability:
    """What a glove's declaration lets a map drive (:func:`drivability`)."""

    #: Per joint, descriptor order: ``True`` = follows the glove.
    armed: Tuple[bool, ...]
    #: Per joint, descriptor order: ``True`` = held by the map.
    held: Tuple[bool, ...]
    #: Joint name -> the channels it reads that cannot drive it.
    lacking: Dict[str, Tuple[str, ...]]
    #: The declaration's refusals of the map's channels, one line each.
    refusals: Tuple[str, ...]


def drivability(table: RetargetTable, declaration, ranges=None) -> Drivability:
    """Which joints of ``table`` a glove with ``declaration`` can drive.

    A channel is unusable when the declaration refuses it as a drive source
    (``declaration.refuse_as_drive_source``: undeclared, uncalibrated, or
    synthesized from channels it reports directly) or when neither the
    declaration's defaults nor the operator's ``ranges`` give it a range. A
    joint that reads an unusable channel is not armed; a held joint is never
    armed and never lacking. Call it once, at bind time."""
    calibration = declaration.calibration(ranges)
    refusals: List[str] = []
    unusable = set()
    for ch in table.channels():
        why = declaration.refuse_as_drive_source(ch)
        if why is not None:
            refusals.append(why)
            unusable.add(ch)
        elif calibration.range_for(ch) is None:
            unusable.add(ch)
    lacking = table.lacking(unusable)
    held = table.held()
    armed = tuple(not h and r.joint.name not in lacking
                  for r, h in zip(table.rows, held))
    return Drivability(armed, held, lacking, tuple(refusals))


def golden_inputs(channels: Sequence[str], seed: int = 0, random_count: int = 24
                  ) -> List[Dict[str, Optional[float]]]:
    """Deterministic flexion inputs for golden vectors over ``channels``:
    all 0, all 0.5, all 1, each channel alone at 1 (others 0.5), each channel
    missing (others 0.5), out-of-range values, and ``random_count`` seeded
    random poses."""
    chs = list(channels)
    out: List[Dict[str, Optional[float]]] = [
        {c: 0.0 for c in chs}, {c: 0.5 for c in chs}, {c: 1.0 for c in chs}]
    for c in chs:
        out.append({**{k: 0.5 for k in chs}, c: 1.0})
    for c in chs:
        out.append({**{k: 0.5 for k in chs}, c: None})
    out.append({c: (-0.25 if i % 2 else 1.25) for i, c in enumerate(chs)})
    rng = random.Random(seed)
    for _ in range(random_count):
        out.append({c: round(rng.random(), 6) for c in chs})
    return out


def golden_vectors(model: str, config=None) -> Dict[str, object]:
    """Golden vectors for ``model``'s map: each input run through the map's
    own ``joint_targets`` (a fresh mapper per input, so smoothing never
    carries over). The document names the table it belongs to by digest."""
    from . import get_retarget  # noqa: PLC0415
    from ..gloves import HandPose  # noqa: PLC0415

    table = retarget_table(model, config)
    vectors = []
    for flex in golden_inputs(table.channels()):
        mapper = get_retarget(model, config=config)
        out = mapper.joint_targets(HandPose("golden", dict(flex)))
        vectors.append({"flex": flex, "targets": [None if v is None else float(v) for v in out]})
    return {"schema": GOLDEN_SCHEMA, "model": model, "table_digest": table.digest(),
            "joints": [j.name for j in table.joints], "vectors": vectors}


def golden_dumps(model: str) -> str:
    """Canonical text of :func:`golden_vectors` for the default map."""
    return _dumps(golden_vectors(model))
